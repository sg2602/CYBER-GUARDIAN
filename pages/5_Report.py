import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import streamlit as st  # noqa: E402

from database import database as db  # noqa: E402
from reports.report_generator import render_html, render_pdf  # noqa: E402
from utils import ui  # noqa: E402

ui.setup("Report")
st.title("📄 Security Audit Report")
a = ui.get_assessment()
if a is None:
    st.info("Not yet assessed. Run the Security Scanner first.")
    st.stop()

st.markdown(f"Assessment **{a['assessment_id']}** · {a['created_at']} · score **{a['score']:.0f}**")
c1, c2, c3 = st.columns(3)
if c1.button("💾 Save assessment to history", type="primary"):
    db.save_assessment(a)
    st.success("Saved (scores, finding IDs and chain IDs only).")
html = render_html(a)
c2.download_button("⬇ Download HTML report", html, file_name=f"{a['assessment_id']}.html", mime="text/html")
try:
    pdf = render_pdf(a)
    c3.download_button("⬇ Download PDF report", pdf, file_name=f"{a['assessment_id']}.pdf", mime="application/pdf")
except ImportError:
    c3.caption("Install reportlab for PDF export.")
st.caption("The report contains no passwords, email bodies, full URLs or manifests.")
if hasattr(st, "iframe"):
    st.iframe(html, height=900)  # report HTML is generated by us and autoescaped by Jinja2
else:  # older Streamlit
    import streamlit.components.v1 as components
    components.html(html, height=900, scrolling=True)
